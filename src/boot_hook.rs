//! Root-manager boot ordering belongs here; stage scripts only forward their name.

use crate::errors::{Error, Result};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Stage {
    Manual,
    Metamount,
    PostMount,
}

impl Stage {
    fn parse(args: &[String]) -> Result<Self> {
        match args {
            [] => Ok(Self::Manual),
            [stage] if stage == "metamount" => Ok(Self::Metamount),
            [stage] if stage == "post-mount" => Ok(Self::PostMount),
            _ => Err(Error::msg("usage: boot [metamount|post-mount]")),
        }
    }
}

pub fn handle(args: &[String]) -> Result<()> {
    dispatch(
        Stage::parse(args)?,
        std::env::var_os("APATCH").as_deref() == Some(std::ffi::OsStr::new("true")),
        crate::pipeline::run_boot_pipeline,
        notify_kernel_su,
    )
}

fn dispatch(
    stage: Stage,
    apatch: bool,
    mount: impl FnOnce() -> Result<()>,
    notify: impl FnOnce(),
) -> Result<()> {
    // APatch runs metamount before module post-fs-data scripts. Bind/VFS sources
    // generated by those scripts must not be exposed until post-mount: opening
    // the source with O_TRUNC would also truncate the system file being read.
    let selected = match stage {
        Stage::Manual => true,
        Stage::Metamount => !apatch,
        Stage::PostMount => apatch,
    };
    if !selected {
        log::info!("skip boot stage {stage:?}: apatch={apatch}");
        return Ok(());
    }
    mount()?;
    if stage == Stage::Metamount && !apatch {
        notify();
    }
    Ok(())
}

fn notify_kernel_su() {
    #[cfg(any(target_os = "linux", target_os = "android"))]
    {
        use crate::sys::process::{CommandSpec, run_command};
        use std::{path::Path, time::Duration};

        if !Path::new("/data/adb/ksud").is_file() {
            return;
        }
        let spec = CommandSpec::new("/data/adb/ksud")
            .operation("notify KernelSU modules mounted")
            .args(["kernel", "notify-module-mounted"])
            .timeout(Duration::from_secs(5));
        if let Err(error) = run_command(&spec) {
            // Match the previous hook: notification failure does not undo successful mounts.
            log::warn!("KernelSU mount notification failed: {error}");
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{cell::Cell, fs, io::Write};

    #[test]
    fn only_the_correct_root_manager_stage_mounts() {
        for (stage, apatch, expected_mounts, expected_notifications) in [
            (Stage::Manual, false, 1, 0),
            (Stage::Manual, true, 1, 0),
            (Stage::Metamount, false, 1, 1),
            (Stage::Metamount, true, 0, 0),
            (Stage::PostMount, false, 0, 0),
            (Stage::PostMount, true, 1, 0),
        ] {
            let mounts = Cell::new(0);
            let notifications = Cell::new(0);
            dispatch(
                stage,
                apatch,
                || {
                    mounts.set(mounts.get() + 1);
                    Ok(())
                },
                || notifications.set(notifications.get() + 1),
            )
            .unwrap();
            assert_eq!(mounts.get(), expected_mounts, "{stage:?}, apatch={apatch}");
            assert_eq!(
                notifications.get(),
                expected_notifications,
                "{stage:?}, apatch={apatch}"
            );
        }
    }

    #[test]
    fn apatch_generated_seapp_file_keeps_stock_rules_before_injection() {
        let fixture = crate::test_support::Fixture::new("apatch-seapp-order");
        let system = fixture.join("stock_seapp_contexts");
        let module = fixture.join("module_seapp_contexts");
        let stock = "isSystemServer=true domain=system_server\n";
        fs::write(&system, stock).unwrap();
        fs::write(&module, "isSystemServer=true domain=old_system_server\n").unwrap();
        let expose_source = || {
            // A hard link models bind/VFS aliasing without privileged mounts.
            fs::remove_file(&system)?;
            fs::hard_link(&module, &system)?;
            Ok(())
        };
        dispatch(Stage::Metamount, true, expose_source, || {}).unwrap();

        // MSD's shell redirection opens O_TRUNC before paste reads the system file.
        let mut generated = fs::File::create(&module).unwrap();
        let original = fs::read_to_string(&system).unwrap();
        writeln!(
            generated,
            "{original}user=_app name=example.module domain=example_app"
        )
        .unwrap();
        drop(generated);

        dispatch(Stage::PostMount, true, expose_source, || {}).unwrap();
        assert_eq!(
            fs::read_to_string(system).unwrap(),
            format!("{stock}user=_app name=example.module domain=example_app\n")
        );
    }

    #[test]
    fn mounting_failure_is_returned_without_notifying_kernel_su() {
        let notifications = Cell::new(0);
        let error = dispatch(
            Stage::Metamount,
            false,
            || Err(Error::msg("mount failed")),
            || notifications.set(notifications.get() + 1),
        )
        .unwrap_err();
        assert!(error.to_string().contains("mount failed"));
        assert_eq!(notifications.get(), 0);
    }

    #[test]
    fn unknown_or_extra_stage_arguments_are_rejected() {
        for args in [
            vec!["late".into()],
            vec!["metamount".into(), "extra".into()],
        ] {
            assert!(Stage::parse(&args).is_err());
        }
    }
}
